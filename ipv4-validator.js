const ipv4Regex = /^(?:(?:25[0-5]|2[0-4][0-9]|1[0-9]{2}|[1-9]?[0-9])\.){3}(?:25[0-5]|2[0-4][0-9]|1[0-9]{2}|[1-9]?[0-9])$/;

const addresses = [
    "192.168.1.1",
    "10.0.0.1",
    "255.255.255.255",
    "0.0.0.0",
    "256.1.1.1",
    "192.168.1",
    "192.168.1.300",
    "192.168.-1.1",
    "192.168.1.1.1",
    "abc.def.ghi.jkl",
    "192.168.01.1"
];

addresses.forEach(address => {
    console.log(`${address}: ${ipv4Regex.test(address)}`);
});